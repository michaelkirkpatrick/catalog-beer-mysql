-- International addresses: one `address` table for every country, replacing
-- `US_addresses`; ISO 3166-2 subdivisions for the 40 regions Google Address
-- Validation covers; telephone as an E.164 string.
--
-- Why one table: a per-country table (BE_addresses, ...) multiplies every JOIN
-- that reads an address (brewer locations, nearby, facets, metrics). The US
-- becomes one row shape among many: its ZIP and state rules move from column
-- types into two CHECK constraints that only bite when countryCode = 'US'.
--
-- Columns, in the vocabulary Google's postalAddress uses:
--   line1             street line (today's address2)      -- required
--   line2             unit / building (today's address1)  -- optional
--   locality          city (today's city)                 -- required
--   dependentLocality sublocality (Vleteren -> Westvleteren; MX colonias)
--   sub_code          ISO 3166-2; required when countryCode = 'US', optional
--                     elsewhere (Brussels has no province; many countries do
--                     not address by region); must belong to countryCode
--   postalCode        '97201-1234', '8640', '1018 AL', 'SW1A 1AA'; US shape
--                     enforced by CHECK, every other shape is Google's answer
--   formatted         JSON array of display lines in the country's own order,
--                     country name excluded (the reader adds it from
--                     country_short_name); rendering an address from fields
--                     needs per-country rules, rendering stored lines needs
--                     none. Backfilled for the copied US rows from the fields.
--   languageCode      postalAddress.languageCode ('nl', 'fr', 'en'); Brussels
--                     is bilingual and the UI needs to know which it holds
--   telephone         E.164 ('+15035550100', '+3257400376'). The bigint of ten
--                     NANP digits could not hold a Belgian number, and a bare
--                     digit string is ambiguous: 3257400376 is both +32 57 40
--                     03 76 and a Texas number. The '+' is what says
--                     "international form", and only a string can carry it.
--   validatedAt       when the validator last accepted it (NULL for the copied
--                     US rows, whose check predates the column)
--   countryCode       always equals location.countryCode; denormalized so the
--                     facet and metric queries need no JOIN. The API refuses a
--                     country change on a location that holds an address, so
--                     the two cannot drift.
--
-- subdivisions: `countryCode` (the 51 existing rows are US), `sub_type` (ISO's
-- category: state, province, region, canton, ...) and `parentCode` (ISO's
-- parent: Belgian provinces sit under regions, Spanish provinces under
-- autonomous communities). Seeded from ISO 3166-2 (Debian iso-codes via
-- pycountry, 2026-10-13) at the level Google reports as an administrative
-- area, which is why Belgium gets regions AND provinces, Spain and Italy get
-- both levels, and Great Britain gets its four countries but not its 200
-- councils. Names are the local official form (West-Vlaanderen, Bayern), not
-- English. The US outlying areas (US-PR, US-VI, US-GU, US-AS, US-MP, US-UM)
-- are added so a Puerto Rico address validated under regionCode US/PR can
-- store the state CASS returns.
--
-- Deploy order: THIS MIGRATION FIRST, then the API. The old code never reads
-- `address`; the new code reads nothing else. `US_addresses` is kept, unread,
-- until the suite is green on the new table, then dropped by
-- 2026-10-XX-drop-us-addresses.sql (written alongside, run after the soak).

CREATE TABLE `address` (
  `locationID`        varchar(36)  NOT NULL,
  `countryCode`       char(2)      NOT NULL,
  `line1`             varchar(255) NOT NULL,
  `line2`             varchar(255) DEFAULT NULL,
  `locality`          varchar(255) NOT NULL,
  `dependentLocality` varchar(255) DEFAULT NULL,
  `sub_code`          varchar(6)   DEFAULT NULL,
  `postalCode`        varchar(20)  DEFAULT NULL,
  `formatted`         json         DEFAULT NULL,
  `languageCode`      varchar(8)   DEFAULT NULL,
  `telephone`         varchar(16)  DEFAULT NULL,
  `validatedAt`       int          DEFAULT NULL,
  PRIMARY KEY (`locationID`),
  KEY `idx_address_country_sub` (`countryCode`,`sub_code`),
  KEY `idx_address_postal` (`countryCode`,`postalCode`),
  CONSTRAINT `fk_address_location` FOREIGN KEY (`locationID`) REFERENCES `location` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_address_sub_code` FOREIGN KEY (`sub_code`) REFERENCES `subdivisions` (`sub_code`),
  CONSTRAINT `chk_address_us_sub` CHECK (`countryCode` <> 'US' OR `sub_code` IS NOT NULL),
  CONSTRAINT `chk_address_us_postal` CHECK (`countryCode` <> 'US' OR `postalCode` REGEXP '^[0-9]{5}(-[0-9]{4})?$'),
  CONSTRAINT `chk_address_tel` CHECK (`telephone` IS NULL OR `telephone` REGEXP '^\\+[1-9][0-9]{6,14}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

ALTER TABLE `subdivisions`
  ADD COLUMN `countryCode` char(2)     NOT NULL DEFAULT 'US' AFTER `sub_code`,
  ADD COLUMN `sub_type`    varchar(32) DEFAULT NULL AFTER `sub_name`,
  ADD COLUMN `parentCode`  varchar(6)  DEFAULT NULL AFTER `sub_type`,
  ADD INDEX `idx_sub_country` (`countryCode`);

UPDATE `subdivisions` SET `sub_type` = IF(`sub_code` = 'US-DC', 'district', 'state') WHERE `countryCode` = 'US';

-- Copy the US rows. zip5 + zip4 fold into postalCode; the ten NANP digits
-- become '+1' + digits; formatted is built from the fields in US order so
-- every row carries display lines from day one.
INSERT INTO `address`
  (`locationID`, `countryCode`, `line1`, `line2`, `locality`, `dependentLocality`, `sub_code`, `postalCode`, `formatted`, `languageCode`, `telephone`, `validatedAt`)
SELECT
  `locationID`,
  'US',
  `address2`,
  NULLIF(`address1`, ''),
  `city`,
  NULL,
  `sub_code`,
  CONCAT(`zip5`, IF(`zip4` IS NULL OR `zip4` = '', '', CONCAT('-', `zip4`))),
  IF(`address1` IS NULL OR `address1` = '',
     JSON_ARRAY(`address2`, CONCAT(`city`, ', ', SUBSTRING(`sub_code`, 4), ' ', `zip5`, IF(`zip4` IS NULL OR `zip4` = '', '', CONCAT('-', `zip4`)))),
     JSON_ARRAY(`address2`, `address1`, CONCAT(`city`, ', ', SUBSTRING(`sub_code`, 4), ' ', `zip5`, IF(`zip4` IS NULL OR `zip4` = '', '', CONCAT('-', `zip4`))))),
  'en',
  IF(`telephone` IS NULL OR `telephone` = 0, NULL, CONCAT('+1', LPAD(`telephone`, 10, '0'))),
  NULL
FROM `US_addresses`;

